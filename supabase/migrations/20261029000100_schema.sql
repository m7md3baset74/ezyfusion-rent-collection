-- Rent collection schema. Money is bigint sen, calendar dates are date, instants are timestamptz.
-- Composite (id, org_id) foreign keys make it impossible for a row to point at another organization's rows.

create extension if not exists btree_gist with schema extensions;

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) > 0),
  created_at timestamptz not null default now()
);

-- A staff member or manager belongs to exactly one organization, so user_id is the primary key.
-- user_id is auth.users.id (no FK: Prisma introspection cannot follow cross-schema references).
create table public.memberships (
  user_id uuid primary key,
  org_id uuid not null references public.organizations (id),
  role text not null check (role in ('manager', 'staff')),
  created_at timestamptz not null default now()
);
create index memberships_org_id_idx on public.memberships (org_id);

create table public.units (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  name text not null check (length(btrim(name)) > 0),
  created_at timestamptz not null default now(),
  unique (org_id, name),
  unique (id, org_id)
);

create table public.tenants (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  user_id uuid unique,
  full_name text not null,
  email text not null,
  -- Tenants edit this column directly through the Data API, so the format is enforced here.
  phone text check (phone ~ '^\+?[0-9][0-9 -]{5,18}[0-9]$'),
  created_at timestamptz not null default now(),
  unique (id, org_id)
);
create index tenants_org_id_idx on public.tenants (org_id);

create table public.leases (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id),
  unit_id uuid not null,
  tenant_id uuid not null,
  start_date date not null,
  end_date date not null,
  monthly_rent_sen bigint not null check (monthly_rent_sen > 0),
  deposit_sen bigint not null check (deposit_sen >= 0),
  created_by uuid,
  created_at timestamptz not null default now(),
  check (end_date >= start_date),
  unique (id, org_id),
  foreign key (unit_id, org_id) references public.units (id, org_id),
  foreign key (tenant_id, org_id) references public.tenants (id, org_id),
  -- Both dates inclusive. Enforced by the database, so two concurrent requests cannot both succeed.
  constraint leases_no_overlap exclude using gist (unit_id with =, daterange(start_date, end_date, '[]') with &&)
);
create index leases_org_id_idx on public.leases (org_id);
create index leases_tenant_id_idx on public.leases (tenant_id);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  lease_id uuid not null,
  kind text not null check (kind in ('deposit', 'rent')),
  period_index integer,
  period_start date,
  period_end date,
  due_date date not null,
  amount_sen bigint not null check (amount_sen >= 0),
  created_at timestamptz not null default now(),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  unique (id, org_id),
  unique nulls not distinct (lease_id, kind, period_index),
  check (
    (kind = 'deposit' and period_index is null and period_start is null and period_end is null)
    or (kind = 'rent' and period_index >= 0 and period_start is not null and period_end is not null and period_end >= period_start)
  )
);
create index invoices_org_id_idx on public.invoices (org_id);

-- id is 'bill_' + 32 hex chars from 16 random bytes, generated by the server (lib/server/bills.ts).
create table public.gateway_bills (
  id text primary key check (id ~ '^bill_[0-9a-f]{32}$'),
  org_id uuid not null,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed')),
  transaction_id text,
  paid_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  unique (id, lease_id)
);
create index gateway_bills_lease_id_idx on public.gateway_bills (lease_id);
create index gateway_bills_org_id_idx on public.gateway_bills (org_id);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  unapplied_sen bigint not null default 0,
  method text not null check (method in ('cash', 'bank_transfer', 'online')),
  status text not null check (status in ('pending_verification', 'approved', 'rejected', 'voided')),
  received_at timestamptz not null,
  slip_path text,
  -- unique: a gateway bill creates at most one payment, ever (the webhook relies on this).
  gateway_bill_id text unique,
  recorded_by uuid, -- null for online payments, which the webhook creates
  decided_by uuid,
  decided_at timestamptz,
  decision_reason text,
  created_at timestamptz not null default now(),
  foreign key (lease_id, org_id) references public.leases (id, org_id),
  foreign key (gateway_bill_id, lease_id) references public.gateway_bills (id, lease_id),
  unique (gateway_bill_id, lease_id), -- redundant with unique(gateway_bill_id); lets Prisma model the 1:1 relation
  unique (id, org_id),
  check (unapplied_sen >= 0 and unapplied_sen <= amount_sen),
  check ((method = 'bank_transfer') = (slip_path is not null)),
  check (slip_path is null or (starts_with(slip_path, org_id::text || '/') and position('..' in slip_path) = 0)),
  check ((method = 'online') = (gateway_bill_id is not null))
);
create index payments_lease_id_idx on public.payments (lease_id);
create index payments_org_received_idx on public.payments (org_id, received_at);

create table public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null,
  payment_id uuid not null,
  invoice_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  created_at timestamptz not null default now(),
  foreign key (payment_id, org_id) references public.payments (id, org_id),
  foreign key (invoice_id, org_id) references public.invoices (id, org_id),
  unique (payment_id, invoice_id)
);
create index payment_allocations_invoice_id_idx on public.payment_allocations (invoice_id);

create table public.audit_log (
  id bigint generated always as identity primary key,
  org_id uuid not null references public.organizations (id),
  actor_id uuid, -- null when the system acted (the gateway webhook)
  action text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_log_org_created_idx on public.audit_log (org_id, created_at);
